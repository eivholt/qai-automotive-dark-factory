"""Measure the private welding cell LCD and illuminated button glass.

Requires numpy and the existing scan generated by prepare_welding_cell.ps1.
Only a small local placement manifest is written. Source meshes, UVs, materials,
and scene.json are never changed. The emitted geometry-derived coordinates and
source hashes stay under ignored assets/; no private payload is shipped here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from prepare_welding_cell import read_mesh


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def plane_frame(normal: np.ndarray) -> np.ndarray:
    normal = np.asarray(normal, dtype=np.float64)
    normal /= np.linalg.norm(normal)
    up = np.array([0., 0., 1.])
    up -= np.dot(up, normal) * normal
    up /= np.linalg.norm(up)
    right = -np.cross(normal, up)
    frame = np.stack((right, up, normal))
    if not np.allclose(frame @ frame.T, np.eye(3), atol=1e-10):
        raise ValueError('Invalid measured cabinet frame')
    return frame


def measure_surface(points, triangles, island: int) -> dict:
    source = triangles[triangles['island'] == island]
    # The scan preserves imported shading normals. Coordinate conversion flips
    # geometric triangle winding, so do not use cross-product sign as outward.
    front = source[source['normals'].mean(axis=1)[:, 1] < -.9]
    if len(front) < 2:
        raise ValueError(f'No front-facing glass for source island {island}')
    xyz = points[front['v']].astype(np.float64)
    areas = np.linalg.norm(np.cross(xyz[:, 1]-xyz[:, 0], xyz[:, 2]-xyz[:, 0]), axis=1) / 2
    normal = np.average(front['normals'].mean(axis=1).astype(np.float64), axis=0, weights=areas)
    frame = plane_frame(normal)
    vertices = points[np.unique(front['v'])].astype(np.float64)
    projected = vertices @ frame.T
    low, high = projected.min(axis=0), projected.max(axis=0)
    center = ((low + high) / 2) @ frame
    if not np.all(np.isfinite(center)):
        raise ValueError('Nonfinite glass placement')
    local_xy = (vertices-center) @ frame[:2].T
    uv = front['uv'].reshape(-1, 2)
    all_vertices = points[np.unique(source['v'])].astype(np.float64)
    return {
        'source_island': island,
        'source_triangles': len(source),
        'front_triangles': len(front),
        'center_cm': center.tolist(),
        'center_parent_local_cm': center.tolist(),
        'center_local_cm': center.tolist(),
        'normal_local': frame[2].tolist(),
        'right_local': frame[0].tolist(),
        'up_local': frame[1].tolist(),
        'normal': frame[2].tolist(),
        'right': frame[0].tolist(),
        'up': frame[1].tolist(),
        'width_cm': float(high[0]-low[0]),
        'height_cm': float(high[1]-low[1]),
        'radius_cm': float(np.max(np.linalg.norm(local_xy, axis=1))),
        'front_depth_range_cm': float(high[2]-low[2]),
        'source_bounds_cm': {'min': all_vertices.min(axis=0).tolist(), 'max': all_vertices.max(axis=0).tolist()},
        'front_uv_bounds': {'min': uv.min(axis=0).astype(float).tolist(), 'max': uv.max(axis=0).astype(float).tolist()},
    }


def generate(root: Path) -> dict:
    scan = root / 'scan'
    mesh_name = 'Car_Body_Welding_Robotics_Cell_robots_screen'
    meshbin = scan / (mesh_name + '.meshbin')
    source = json.loads((scan / 'source.json').read_text(encoding='utf-8'))
    scene = json.loads((root / 'scene.json').read_text(encoding='utf-8'))
    parent_id = 'SM_Background_robots_screen'
    parents = [c for c in scene['components'] if c['id'] == parent_id]
    if len(parents) != 1:
        raise ValueError('Expected one source cabinet glass component')
    parent = parents[0]
    if parent['location_cm'] != [0., 0., 0.] or parent['rotation_deg'] != [0, 0, 0] or parent['scale_xyz'] != [1., 1., 1.] or parent['parent_joint']:
        raise ValueError('Cabinet placement currently requires the authored identity parent transform')
    points, triangles, _ = read_mesh(meshbin)
    islands = sorted(int(i) for i in np.unique(triangles['island']))
    if islands != list(range(13)):
        raise ValueError('Source cabinet topology changed: expected 13 glass islands')
    surfaces = [measure_surface(points, triangles, i) for i in islands]
    screen = max(surfaces, key=lambda s: s['width_cm']*s['height_cm'])
    status = min(surfaces, key=lambda s: s['width_cm']*s['height_cm'])
    buttons = [s for s in surfaces if s is not screen and s is not status]
    if screen['source_island'] != 0 or status['source_island'] != 1 or len(buttons) != 11:
        raise ValueError('Unexpected cabinet display topology')
    if not (40 < screen['width_cm'] < 46 and 30 < screen['height_cm'] < 35 and screen['front_depth_range_cm'] < .01):
        raise ValueError('LCD no longer resembles the expected flat display')
    screen['id'] = 'main_lcd'
    screen['shape'] = 'rectangle'
    status['id'] = 'power_status_led'
    status['shape'] = 'rounded_rectangle'
    status['source_color'] = 'green'
    status['swatch_color'] = 'green'
    for button in buttons:
        if not (3.8 < button['width_cm'] < 4.5 and 3.8 < button['height_cm'] < 4.5 and button['front_depth_range_cm'] < .4):
            raise ValueError('Unexpected button glass dimensions')
        button['id'] = f"button_{button['source_island']:02d}"
        button['shape'] = 'circle'
        # Original face UVs select the red or green swatch in the private atlas.
        # These colors are decorative controls, never model pass/fail labels.
        button['source_color'] = 'red' if button['front_uv_bounds']['max'][0] < .07 else 'green'
        button['swatch_color'] = button['source_color']
    texture_name = 'Automation_Robotic_Bag_Palletizing_Cel_screen.jpg'
    texture = root.parents[1] / 'Autodesk_FBX_2009' / texture_name
    if not texture.is_file():
        raise ValueError('The original local display texture is required')
    return {
        'version': 1,
        'schema_version': 1,
        'parent_mesh': parent_id,
        'kind': 'source_fitted_control_cabinet_glass',
        'coordinates': 'Unreal centimetres; identity parent means local equals world',
        'parent_component_id': parent_id,
        'parent_asset_path': parent['asset_path'],
        'parent_transform': {k: parent[k] for k in ('location_cm', 'rotation_deg', 'scale_xyz')},
        'source_mesh': mesh_name,
        'source_meshbin_sha256': digest(meshbin),
        'source_fbx_sha256': source['source_sha256'].lower(),
        'source_texture': texture_name,
        'source_texture_sha256': digest(texture),
        'front_selection': 'Imported mean shading normal Y < -0.9; area-weighted frame and projected vertex bounds',
        'plane_mask_half_depth_cm': .35,
        'material_scope': 'Only this 13-island source glass component; no housing or mesh reimport',
        'screen': screen,
        'status_led': status,
        'buttons': [status] + buttons,
        'counts': {'cabinets': 1, 'lcds': 1, 'status_leds': 1, 'buttons': len(buttons), 'led_controls': 1 + len(buttons), 'green_buttons': sum(b['source_color'] == 'green' for b in buttons), 'red_buttons': sum(b['source_color'] == 'red' for b in buttons)},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('assets/derived/welding_cell'))
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check', action='store_true', help='Verify an existing manifest without writing')
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output or root / 'control_cabinets.json'
    result = generate(root)
    encoded = (json.dumps(result, indent=2, allow_nan=False) + '\n').encode('utf-8')
    if args.check:
        if output.read_bytes() != encoded:
            raise SystemExit('Control cabinet placement manifest is stale')
        print('CONTROL_CABINET_PLACEMENTS_VERIFIED ' + json.dumps(result['counts']))
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(encoded)
        print('CONTROL_CABINET_PLACEMENTS_READY ' + json.dumps(result['counts']))


if __name__ == '__main__':
    main()
